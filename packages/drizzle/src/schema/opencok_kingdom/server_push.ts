import { sql } from "drizzle-orm";
import { bigint, check, index, integer, primaryKey, varchar } from "drizzle-orm/pg-core";
import { bytea } from "../../types";
import { opencok_kingdom } from "../namespaces";

export const server_push = opencok_kingdom.table(
    "server_push",
    {
        "uid": varchar("uid", { length: 40 }).notNull(),
        "type": integer("type").default(sql.raw("0")),
        "mailType": integer("mailType").default(sql.raw("0")),
        "startTime": bigint("startTime", { mode: "bigint" }),
        "endTime": bigint("endTime", { mode: "bigint" }),
        "regStartTime": bigint("regStartTime", { mode: "bigint" }),
        "regEndTime": bigint("regEndTime", { mode: "bigint" }),
        "lastOnlineTimeBegin": bigint("lastOnlineTimeBegin", { mode: "bigint" }),
        "lastOnlineTime": bigint("lastOnlineTime", { mode: "bigint" }),
        "levelMin": integer("levelMin"),
        "levelMax": integer("levelMax"),
        "title": bytea("title"),
        "contents": bytea("contents"),
        "reward": bytea("reward"),
        "updateVersion": varchar("updateVersion", { length: 40 }),
        "state": integer("state"),
        "parse": integer("parse"),
        "notification": bytea("notification"),
        "reply": integer("reply"),
        "likeStatus": integer("likeStatus"),
        "confirm": integer("confirm").default(sql.raw("0")),
        "platform": varchar("platform", { length: 40 }),
        "itemIdFlag": integer("itemIdFlag").default(sql.raw("0")),
        "activityId": varchar("activityId", { length: 64 }),
        "countries": varchar("countries", { length: 256 }),
        "deviceLimit": integer("deviceLimit"),
        "CDKeySeries": integer("CDKeySeries"),
        "bind": integer("bind").default(sql.raw("0")),
        "bLvMin": integer("bLvMin").default(sql.raw("0")),
        "bLvMax": integer("bLvMax").default(sql.raw("0")),
        "HDflag": integer("HDflag").default(sql.raw("0")),
        "mbLevel": integer("mbLevel").default(sql.raw("0")),
        "setReceiveTime": integer("setReceiveTime").default(sql.raw("0")),
        "tag": varchar("tag", { length: 100 }),
    },
    (table) => [
        primaryKey({ name: "server_push_PRIMARY", columns: [table["uid"]] }),
        index("server_push_index_startTime").on(sql.raw("\"startTime\"")),
        index("server_push_index_stateType").on(sql.raw("\"state\""), sql.raw("\"type\"")),
        check("server_push_title_length", sql.raw("octet_length(\"title\") <= 65535")),
        check("server_push_contents_length", sql.raw("octet_length(\"contents\") <= 16777215")),
        check("server_push_reward_length", sql.raw("octet_length(\"reward\") <= 65535")),
        check(
            "server_push_notification_length",
            sql.raw("octet_length(\"notification\") <= 65535"),
        ),
    ],
);
