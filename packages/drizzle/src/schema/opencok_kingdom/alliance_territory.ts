import { sql } from "drizzle-orm";
import {
    bigint,
    index,
    integer,
    numeric,
    primaryKey,
    uniqueIndex,
    varchar,
} from "drizzle-orm/pg-core";
import { opencok_kingdom } from "../namespaces";

export const alliance_territory = opencok_kingdom.table(
    "alliance_territory",
    {
        "uid": varchar("uid", { length: 255 }).notNull(),
        "pointId": integer("pointId"),
        "atWorldId": integer("atWorldId").notNull().default(sql.raw("0")),
        "towerPoint": integer("towerPoint"),
        "type": integer("type"),
        "resType": integer("resType"),
        "num": integer("num").default(sql.raw("1")),
        "allianceId": varchar("allianceId", { length: 255 }).notNull(),
        "allianceName": varchar("allianceName", { length: 255 }).notNull(),
        "allianceAbbr": varchar("allianceAbbr", { length: 255 }),
        "stat": integer("stat").default(sql.raw("0")),
        "active": integer("active").default(sql.raw("0")),
        "level": integer("level").default(sql.raw("0")),
        "maxDef": integer("maxDef"),
        "curDef": integer("curDef"),
        "createId": varchar("createId", { length: 255 }),
        "ownerId": varchar("ownerId", { length: 255 }),
        "pic": varchar("pic", { length: 255 }),
        "name": varchar("name", { length: 255 }),
        "flag": varchar("flag", { length: 255 }),
        "buildingSpd": numeric("buildingSpd", { precision: 20, scale: 10, mode: "number" }).default(
            sql.raw("0.0000000000"),
        ),
        "updateTime": bigint("updateTime", { mode: "bigint" }),
        "startTime": bigint("startTime", { mode: "bigint" }),
        "lastUpdateTime": bigint("lastUpdateTime", { mode: "bigint" }),
        "donateItemNum": integer("donateItemNum"),
        "arrowHarmPower": integer("arrowHarmPower").default(sql.raw("0")),
        "neighbour": varchar("neighbour", { length: 1000 }),
        "createTime": bigint("createTime", { mode: "bigint" }).default(sql.raw("0")),
        "activateTime": bigint("activateTime", { mode: "bigint" }),
        "trapNum": integer("trapNum").default(sql.raw("0")),
        "reduceTime": bigint("reduceTime", { mode: "bigint" }).default(sql.raw("0")),
        "skinsStr": varchar("skinsStr", { length: 50 }).default(sql.raw("''")),
        "skinExpStr": varchar("skinExpStr", { length: 255 }).default(sql.raw("''")),
        "nextChangeSkinTime": bigint("nextChangeSkinTime", { mode: "bigint" }).default(
            sql.raw("0"),
        ),
        "activeSkin": varchar("activeSkin", { length: 10 }).default(sql.raw("''")),
    },
    (table) => [
        primaryKey({ name: "alliance_territory_PRIMARY", columns: [table["uid"]] }),
        uniqueIndex("alliance_territory_pointId_worldId_idx").on(
            sql.raw("\"pointId\""),
            sql.raw("\"atWorldId\""),
        ),
        index("alliance_territory_alliance_idx").on(sql.raw("\"allianceId\"")),
        index("alliance_territory_update_idx").on(sql.raw("\"updateTime\"")),
        index("alliance_territory_start_idx").on(sql.raw("\"startTime\"")),
        index("alliance_territory_lastup_idx").on(sql.raw("\"lastUpdateTime\"")),
        index("alliance_territory_tower_idx").on(sql.raw("\"towerPoint\"")),
        index("alliance_territory_pointId_idx").on(sql.raw("\"pointId\"")),
    ],
);
