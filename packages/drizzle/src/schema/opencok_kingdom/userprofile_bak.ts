import { sql } from "drizzle-orm";
import { bigint, index, integer, primaryKey, varchar } from "drizzle-orm/pg-core";
import { opencok_kingdom } from "../namespaces";

export const userprofile_bak = opencok_kingdom.table(
  "userprofile_bak",
  {
    "uid": varchar("uid", { length: 255 }).notNull().default(sql.raw("''")),
    "name": varchar("name", { length: 255 }).notNull(),
    "level": integer("level").notNull(),
    "exp": integer("exp").notNull(),
    "gold": bigint("gold", { mode: "bigint" }).notNull().default(sql.raw("0")),
    "paidGold": bigint("paidGold", { mode: "bigint" }).default(sql.raw("0")),
    "payTotal": bigint("payTotal", { mode: "bigint" }).notNull().default(sql.raw("0")),
    "parseRegisterId": varchar("parseRegisterId", { length: 255 }),
    "gcmRegisterId": varchar("gcmRegisterId", { length: 255 }),
    "openedPos": varchar("openedPos", { length: 500 }),
    "pic": varchar("pic", { length: 40 }),
    "picVer": integer("picVer").default(sql.raw("0")),
    "country": varchar("country", { length: 40 }).notNull(),
    "allianceId": varchar("allianceId", { length: 40 }),
    "chNameCount": varchar("chNameCount", { length: 255 }).default(sql.raw("'0'")),
    "worldPoint": integer("worldPoint"),
    "deviceId": varchar("deviceId", { length: 255 }),
    "deviceUuid": varchar("deviceUuid", { length: 200 }),
    "gaid": varchar("gaid", { length: 40 }),
    "platform": varchar("platform", { length: 40 }),
    "pf": varchar("pf", { length: 40 }).default(sql.raw("'csmod_games'")),
    "lang": varchar("lang", { length: 40 }),
    "mt": varchar("mt", { length: 255 }),
    "appVersion": varchar("appVersion", { length: 40 }),
    "gmFlag": integer("gmFlag").default(sql.raw("0")),
    "regTime": bigint("regTime", { mode: "bigint" }).notNull().default(sql.raw("0")),
    "offLineTime": bigint("offLineTime", { mode: "bigint" }).default(sql.raw("0")),
    "banTime": bigint("banTime", { mode: "bigint" }).default(sql.raw("0")),
    "banType": integer("banType").default(sql.raw("0")),
    "banTimes": integer("banTimes").default(sql.raw("0")),
    "chatBanTime": bigint("chatBanTime", { mode: "bigint" }).default(sql.raw("0")),
    "banGMName": varchar("banGMName", { length: 255 }),
    "noticeBanTime": bigint("noticeBanTime", { mode: "bigint" }).default(sql.raw("0")),
    "lastOnlineTime": bigint("lastOnlineTime", { mode: "bigint" }).default(sql.raw("0")),
    "gmail": varchar("gmail", { length: 255 }),
    "serverId": integer("serverId"),
    "crossFightSrcServerId": integer("crossFightSrcServerId").notNull().default(sql.raw("-1")),
    "lastModGoldGetTime": bigint("lastModGoldGetTime", { mode: "bigint" }).default(sql.raw("0")),
    "modGoldGetTimeInterval": bigint("modGoldGetTimeInterval", { mode: "bigint" }).default(
      sql.raw("0"),
    ),
    "modGoldAmount": bigint("modGoldAmount", { mode: "bigint" }).default(sql.raw("0")),
    "beTrainingModTime": bigint("beTrainingModTime", { mode: "bigint" }).default(sql.raw("0")),
    "guideStep": varchar("guideStep", { length: 255 }).default(sql.raw("''")),
    "payRiskFactor": integer("payRiskFactor").default(sql.raw("0")),
    "phoneDevice": varchar("phoneDevice", { length: 40 }),
    "crystal": bigint("crystal", { mode: "bigint" }).default(sql.raw("0")),
  },
  (table) => [
    primaryKey({ name: "userprofile_bak_PRIMARY", columns: [table["uid"]] }),
    index("userprofile_bak_name_index").on(sql.raw('"name"')),
    index("userprofile_bak_time_level_index").on(
      sql.raw('"regTime"'),
      sql.raw('"level"'),
      sql.raw('"lastOnlineTime"'),
      sql.raw('"pf"'),
    ),
    index("userprofile_bak_allianceid_lasttime_index").on(
      sql.raw('"allianceId"'),
      sql.raw('"lastOnlineTime"'),
    ),
    index("userprofile_bak_lang_index").on(sql.raw('"lang"')),
  ],
);
