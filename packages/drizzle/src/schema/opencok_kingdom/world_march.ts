import { sql } from "drizzle-orm";
import {
  bigint,
  check,
  index,
  integer,
  numeric,
  primaryKey,
  real,
  varchar,
} from "drizzle-orm/pg-core";
import { bytea } from "../../types";
import { opencok_kingdom } from "../namespaces";

export const world_march = opencok_kingdom.table(
  "world_march",
  {
    "uuid": varchar("uuid", { length: 40 }).notNull().default(sql.raw("''")),
    "ownerUid": varchar("ownerUid", { length: 40 }),
    "ownerId": integer("ownerId").notNull(),
    "ownerName": varchar("ownerName", { length: 255 }),
    "ownerColor": integer("ownerColor"),
    "allianceId": varchar("allianceId", { length: 40 }),
    "teamId": varchar("teamId", { length: 40 }),
    "armyInfo": bytea("armyInfo"),
    "type": integer("type").notNull(),
    "targetId": integer("targetId").notNull(),
    "targetType": integer("targetType"),
    "targetUid": varchar("targetUid", { length: 255 }),
    "marchStartTime": bigint("marchStartTime", { mode: "bigint" }).notNull(),
    "marchTime": integer("marchTime"),
    "marchArrivalTime": bigint("marchArrivalTime", { mode: "bigint" }),
    "returnStartTime": bigint("returnStartTime", { mode: "bigint" }),
    "arrivalTime": bigint("arrivalTime", { mode: "bigint" }),
    "exploreTime": bigint("exploreTime", { mode: "bigint" }),
    "exploreReport": bytea("exploreReport"),
    "collectSpd": real("collectSpd"),
    "changeCollectSpdTime": bigint("changeCollectSpdTime", { mode: "bigint" }),
    "collectedBeforeSpd": bigint("collectedBeforeSpd", { mode: "bigint" }),
    "resLevel": integer("resLevel"),
    "plunderRes": varchar("plunderRes", { length: 2048 }),
    "retrieveRes": varchar("retrieveRes", { length: 1024 }),
    "state": integer("state"),
    "extraParam": integer("extraParam").default(sql.raw("0")),
    "blackLandMarchTime": varchar("blackLandMarchTime", { length: 2048 }),
    "monsterArmyCount": integer("monsterArmyCount"),
    "monsterLevel": integer("monsterLevel"),
    "monsterInfo": varchar("monsterInfo", { length: 4000 }),
    "territoryStartTime": bigint("territoryStartTime", { mode: "bigint" }),
    "territoryUpdateTime": bigint("territoryUpdateTime", { mode: "bigint" }),
    "territoryStat": integer("territoryStat").default(sql.raw("0")),
    "buildingKillArmy": bytea("buildingKillArmy"),
    "slowDown": integer("slowDown").default(sql.raw("0")),
    "worldId": integer("worldId").notNull().default(sql.raw("0")),
    "isDuelSkill": integer("isDuelSkill").default(sql.raw("0")),
    "fightSide": integer("fightSide").default(sql.raw("0")),
    "occupyResourceEndTime": bigint("occupyResourceEndTime", { mode: "bigint" }).default(
      sql.raw("0"),
    ),
    "superTeam": integer("superTeam").default(sql.raw("0")),
    "honourWatchtower": integer("honourWatchtower").default(sql.raw("0")),
    "npcDropAdd": numeric("npcDropAdd", { precision: 8, scale: 2, mode: "number" }),
    "record": integer("record"),
    "stamina": integer("stamina").default(sql.raw("0")),
    "singleCureAdd": numeric("singleCureAdd", { precision: 8, scale: 2, mode: "number" }).default(
      sql.raw("0.00"),
    ),
  },
  (table) => [
    primaryKey({ name: "world_march_PRIMARY", columns: [table["uuid"]] }),
    index("world_march_ownerId_index_001").on(sql.raw('"ownerUid"')),
    index("world_march_targetUid_index").on(sql.raw('"targetUid"')),
    check("world_march_armyInfo_length", sql.raw('octet_length("armyInfo") <= 65535')),
    check("world_march_exploreReport_length", sql.raw('octet_length("exploreReport") <= 65535')),
    check(
      "world_march_buildingKillArmy_length",
      sql.raw('octet_length("buildingKillArmy") <= 65535'),
    ),
  ],
);
