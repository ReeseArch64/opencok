import { sql } from "drizzle-orm";
import { bigint, check, index, integer, numeric, primaryKey, smallint, varchar } from "drizzle-orm/pg-core";
import { cokdb1 } from "../namespaces";

export const userprofile_active = cokdb1.table("userprofile_active", {
  "uuid": integer("uuid").notNull().generatedByDefaultAsIdentity({"name":"userprofile_active_uuid_seq","startWith":1}),
  "uid": varchar("uid", { length: 30 }).notNull(),
  "level": smallint("level").default(sql.raw("0")),
  "build_level": smallint("build_level").default(sql.raw("0")),
  "honour_level": smallint("honour_level").default(sql.raw("0")),
  "parse_register_id": varchar("parse_register_id", { length: 100 }).default(sql.raw("''")),
  "country": varchar("country", { length: 20 }).default(sql.raw("''")),
  "pf": varchar("pf", { length: 20 }).default(sql.raw("''")),
  "lang": varchar("lang", { length: 20 }).default(sql.raw("''")),
  "vip_level": smallint("vip_level").default(sql.raw("0")),
  "svip_level": smallint("svip_level").default(sql.raw("0")),
  "total_pay": integer("total_pay").default(sql.raw("0")),
  "last_online_time": bigint("last_online_time", { mode: "bigint" }).default(sql.raw("0")),
  "ban_time": bigint("ban_time", { mode: "bigint" }).default(sql.raw("0")),
  "status": smallint("status").default(sql.raw("0")),
  "push_count": integer("push_count").default(sql.raw("0")),
  "pay_sum": numeric("pay_sum", { precision: 10, scale: 2, mode: "number" }).default(sql.raw("0.00")),
  "power": bigint("power", { mode: "bigint" }).default(sql.raw("0")),
  "user_name": varchar("user_name", { length: 255 }).default(sql.raw("''")),
  "most_ip": varchar("most_ip", { length: 16 }).default(sql.raw("''")),
  "app_version": varchar("app_version", { length: 40 }).default(sql.raw("''")),
  "last_pay_time": bigint("last_pay_time", { mode: "bigint" }),
  "gmail": varchar("gmail", { length: 255 }),
  "reg_time": bigint("reg_time", { mode: "bigint" }),
  "reg_ip": varchar("reg_ip", { length: 20 }),
  "type": integer("type"),
  "deviceId": varchar("deviceId", { length: 255 }),
  "exp": integer("exp"),
  "offLineTime": bigint("offLineTime", { mode: "bigint" }),
  "googleAccount": varchar("googleAccount", { length: 255 }),
  "facebookAccount": varchar("facebookAccount", { length: 255 }),
}, (table) => [
  primaryKey({ name: "userprofile_active_PRIMARY", columns: [table["uuid"]] }),
  index("userprofile_active_uid").on(sql.raw("\"uid\"")),
  check("userprofile_active_level_range", sql.raw("\"level\" BETWEEN -128 AND 127")),
  check("userprofile_active_build_level_range", sql.raw("\"build_level\" BETWEEN -128 AND 127")),
  check("userprofile_active_honour_level_range", sql.raw("\"honour_level\" BETWEEN -128 AND 127")),
  check("userprofile_active_vip_level_range", sql.raw("\"vip_level\" BETWEEN -128 AND 127")),
  check("userprofile_active_svip_level_range", sql.raw("\"svip_level\" BETWEEN -128 AND 127")),
  check("userprofile_active_status_range", sql.raw("\"status\" BETWEEN -128 AND 127")),
]);
