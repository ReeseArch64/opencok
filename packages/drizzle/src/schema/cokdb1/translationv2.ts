import { sql } from "drizzle-orm";
import { check, index, integer, primaryKey, varchar } from "drizzle-orm/pg-core";
import { bytea } from "../../types";
import { cokdb1 } from "../namespaces";

export const translationv2 = cokdb1.table("translationv2", {
  "id": varchar("id", { length: 255 }).notNull(),
  "en": bytea("en"),
  "zh-Hans": bytea("zh-Hans"),
  "zh-Hant": bytea("zh-Hant"),
  "ja": bytea("ja"),
  "ko": bytea("ko"),
  "ru": bytea("ru"),
  "es": bytea("es"),
  "ms": bytea("ms"),
  "fr": bytea("fr"),
  "de": bytea("de"),
  "it": bytea("it"),
  "pt": bytea("pt"),
  "count": integer("count").default(sql.raw("0")),
}, (table) => [
  primaryKey({ name: "translationv2_PRIMARY", columns: [table["id"]] }),
  index("translationv2_index_en").on(sql.raw("substring(\"en\" from 1 for 50)")),
  index("translationv2_index_zh-Hans").on(sql.raw("substring(\"zh-Hans\" from 1 for 20)")),
  index("translationv2_index_zh-Hant").on(sql.raw("substring(\"zh-Hant\" from 1 for 20)")),
  index("translationv2_index_ja").on(sql.raw("substring(\"ja\" from 1 for 20)")),
  index("translationv2_index_ko").on(sql.raw("substring(\"ko\" from 1 for 20)")),
  index("translationv2_index_ru").on(sql.raw("substring(\"ru\" from 1 for 20)")),
  index("translationv2_index_es").on(sql.raw("substring(\"es\" from 1 for 20)")),
  index("translationv2_index_ms").on(sql.raw("substring(\"ms\" from 1 for 20)")),
  index("translationv2_index_fr").on(sql.raw("substring(\"fr\" from 1 for 20)")),
  index("translationv2_index_de").on(sql.raw("substring(\"de\" from 1 for 20)")),
  index("translationv2_index_it").on(sql.raw("substring(\"it\" from 1 for 20)")),
  index("translationv2_index_pt").on(sql.raw("substring(\"pt\" from 1 for 20)")),
  index("translationv2_index_count").on(sql.raw("\"count\"")),
  check("translationv2_en_length", sql.raw("octet_length(\"en\") <= 65535")),
  check("translationv2_zh-Hans_length", sql.raw("octet_length(\"zh-Hans\") <= 65535")),
  check("translationv2_zh-Hant_length", sql.raw("octet_length(\"zh-Hant\") <= 65535")),
  check("translationv2_ja_length", sql.raw("octet_length(\"ja\") <= 65535")),
  check("translationv2_ko_length", sql.raw("octet_length(\"ko\") <= 65535")),
  check("translationv2_ru_length", sql.raw("octet_length(\"ru\") <= 65535")),
  check("translationv2_es_length", sql.raw("octet_length(\"es\") <= 65535")),
  check("translationv2_ms_length", sql.raw("octet_length(\"ms\") <= 65535")),
  check("translationv2_fr_length", sql.raw("octet_length(\"fr\") <= 65535")),
  check("translationv2_de_length", sql.raw("octet_length(\"de\") <= 65535")),
  check("translationv2_it_length", sql.raw("octet_length(\"it\") <= 65535")),
  check("translationv2_pt_length", sql.raw("octet_length(\"pt\") <= 65535")),
]);
