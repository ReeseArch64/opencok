import { sql } from "drizzle-orm";
import { bigint, check, index, integer, primaryKey, varchar } from "drizzle-orm/pg-core";
import { bytea } from "../../types";
import { cokdb1 } from "../namespaces";

export const worldpoint = cokdb1.table("worldpoint", {
  "id": integer("id").notNull(),
  "worldId": integer("worldId").notNull().default(sql.raw("0")),
  "x": integer("x").notNull(),
  "y": integer("y").notNull(),
  "areaId": integer("areaId").notNull(),
  "monsterAreaId": integer("monsterAreaId"),
  "bornAreaId": integer("bornAreaId"),
  "gridType": integer("gridType").notNull(),
  "grid2Type": integer("grid2Type").notNull(),
  "pointType": integer("pointType").notNull(),
  "pointItem": varchar("pointItem", { length: 255 }),
  "territoryAlliance": varchar("territoryAlliance", { length: 255 }),
  "territoryId": integer("territoryId"),
  "active": integer("active"),
  "relicAreaId": varchar("relicAreaId", { length: 255 }),
  "resLevel": integer("resLevel").notNull(),
  "resCostValue": integer("resCostValue").notNull().default(sql.raw("0")),
  "resInitValue": integer("resInitValue").notNull(),
  "ownerId": varchar("ownerId", { length: 255 }),
  "ownerName": varchar("ownerName", { length: 255 }),
  "allianceId": varchar("allianceId", { length: 40 }),
  "cityDefValue": integer("cityDefValue"),
  "startOccupyTime": bigint("startOccupyTime", { mode: "bigint" }).default(sql.raw("0")),
  "ownerMarchUUid": varchar("ownerMarchUUid", { length: 40 }),
  "flushTime": bigint("flushTime", { mode: "bigint" }).default(sql.raw("0")),
  "fireTime": bigint("fireTime", { mode: "bigint" }),
  "shieldTime": bigint("shieldTime", { mode: "bigint" }).default(sql.raw("0")),
  "startTime": bigint("startTime", { mode: "bigint" }),
  "monsterInfo": bytea("monsterInfo"),
  "resourceShieldTime": bigint("resourceShieldTime", { mode: "bigint" }).default(sql.raw("0")),
  "monsterCastleState": integer("monsterCastleState").default(sql.raw("0")),
  "monsterCurrHP": integer("monsterCurrHP").default(sql.raw("0")),
  "flushFlag": integer("flushFlag").default(sql.raw("0")),
  "sendHeartDurationTime": bigint("sendHeartDurationTime", { mode: "bigint" }).default(sql.raw("0")),
  "heartType": varchar("heartType", { length: 5 }),
  "cannonFireTime": bigint("cannonFireTime", { mode: "bigint" }),
  "trap": varchar("trap", { length: 255 }),
  "reserve": bigint("reserve", { mode: "bigint" }).default(sql.raw("0")),
}, (table) => [
  primaryKey({ name: "worldpoint_PRIMARY", columns: [table["id"], table["worldId"]] }),
  index("worldpoint_world_res_area_id").on(sql.raw("\"areaId\""), sql.raw("\"gridType\"")),
  index("worldpoint_world_monster_area_id").on(sql.raw("\"monsterAreaId\""), sql.raw("\"pointType\""), sql.raw("\"gridType\""), sql.raw("\"ownerId\""), sql.raw("\"grid2Type\"")),
  index("worldpoint_world_pointType_flushTime_index").on(sql.raw("\"pointType\""), sql.raw("\"pointItem\""), sql.raw("\"flushTime\""), sql.raw("\"gridType\""), sql.raw("\"grid2Type\"")),
  index("worldpoint_world_xy_type_country_index").on(sql.raw("\"x\""), sql.raw("\"y\""), sql.raw("\"pointType\"")),
  index("worldpoint_worldId_pointType_gridType_grid2Type").on(sql.raw("\"worldId\""), sql.raw("\"pointType\""), sql.raw("\"gridType\""), sql.raw("\"grid2Type\"")),
  check("worldpoint_monsterInfo_length", sql.raw("octet_length(\"monsterInfo\") <= 65535")),
]);
