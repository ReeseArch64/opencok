import { sql } from "drizzle-orm";
import { bigint, index, integer, primaryKey, varchar } from "drizzle-orm/pg-core";
import { cokdb1 } from "../namespaces";

export const alliance = cokdb1.table("alliance", {
  "uid": varchar("uid", { length: 40 }).notNull(),
  "alliancename": varchar("alliancename", { length: 40 }),
  "abbr": varchar("abbr", { length: 10 }),
  "abbrRename": integer("abbrRename").default(sql.raw("0")),
  "intro": varchar("intro", { length: 200 }),
  "announce": varchar("announce", { length: 200 }),
  "icon": varchar("icon", { length: 40 }),
  "language": varchar("language", { length: 40 }),
  "country": varchar("country", { length: 40 }),
  "curMember": integer("curMember").default(sql.raw("0")),
  "maxMember": integer("maxMember"),
  "recruit": integer("recruit"),
  "oldfightpower": integer("oldfightpower"),
  "giftlevel": integer("giftlevel").default(sql.raw("0")),
  "alliancepoint": bigint("alliancepoint", { mode: "bigint" }),
  "reicon": integer("reicon").default(sql.raw("0")),
  "rankone": varchar("rankone", { length: 10 }),
  "ranktwo": varchar("ranktwo", { length: 10 }),
  "rankthree": varchar("rankthree", { length: 10 }),
  "rankfour": varchar("rankfour", { length: 10 }),
  "rankfive": varchar("rankfive", { length: 10 }),
  "createtime": bigint("createtime", { mode: "bigint" }).notNull(),
  "dau": integer("dau").default(sql.raw("0")),
  "rallyPoint": integer("rallyPoint"),
  "ally": varchar("ally", { length: 255 }),
  "enemy": varchar("enemy", { length: 255 }),
  "other": varchar("other", { length: 255 }),
  "powerRestriction": bigint("powerRestriction", { mode: "bigint" }).default(sql.raw("0")),
  "castleRestriction": integer("castleRestriction").default(sql.raw("0")),
  "camp": integer("camp").default(sql.raw("0")),
  "crossFightEnemy": varchar("crossFightEnemy", { length: 255 }),
  "ckfThroneFightFlag": integer("ckfThroneFightFlag").default(sql.raw("0")),
  "cdfIndex": integer("cdfIndex"),
  "cdfVersion": integer("cdfVersion"),
  "targetScience": varchar("targetScience", { length: 255 }),
  "permission": varchar("permission", { length: 255 }),
  "wood": bigint("wood", { mode: "bigint" }).default(sql.raw("0")),
  "food": bigint("food", { mode: "bigint" }).default(sql.raw("0")),
  "iron": bigint("iron", { mode: "bigint" }).default(sql.raw("0")),
  "stone": bigint("stone", { mode: "bigint" }).default(sql.raw("0")),
  "sandstone": bigint("sandstone", { mode: "bigint" }).default(sql.raw("0")),
  "diamond": bigint("diamond", { mode: "bigint" }).default(sql.raw("0")),
  "marble": bigint("marble", { mode: "bigint" }).default(sql.raw("0")),
  "granite": bigint("granite", { mode: "bigint" }).default(sql.raw("0")),
  "limestone": bigint("limestone", { mode: "bigint" }).default(sql.raw("0")),
  "donateItem": varchar("donateItem", { length: 255 }),
  "bannerStyle": varchar("bannerStyle", { length: 50 }).notNull(),
  "taskNum": integer("taskNum").default(sql.raw("0")),
  "taskLimit": varchar("taskLimit", { length: 255 }),
  "taskFlushTime": bigint("taskFlushTime", { mode: "bigint" }).default(sql.raw("0")),
}, (table) => [
  primaryKey({ name: "alliance_PRIMARY", columns: [table["uid"]] }),
  index("alliance_name_idx").on(sql.raw("\"alliancename\"")),
]);
