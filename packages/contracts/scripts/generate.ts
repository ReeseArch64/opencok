// Formatting is part of generation, so --check compares the exact committed output.
async function formatted(command: string[], text: string)
{
    const child = Bun.spawn(command, {
        stdin: new TextEncoder().encode(text),
        stdout: "pipe",
        stderr: "pipe",
    });
    const result = await new Response(child.stdout).text();
    if ((await child.exited) !== 0)
    {
        throw new Error(await new Response(child.stderr).text());
    }
    return result;
}
go = await formatted(["gofmt"], go);
// dart format accepts files, not stdin. Keep the temporary file outside the repo.
const temp = await import("node:fs/promises");
const dir = await temp.mkdtemp("/tmp/opencok-contracts-");
try
{
    const path = dir + "/world.dart";
    await Bun.write(path, dart);
    const proc = Bun.spawn(["dart", "format", path], {
        stdout: "pipe",
        stderr: "pipe",
    });
    if ((await proc.exited) !== 0)
    {
        throw new Error(await new Response(proc.stderr).text());
    }
    dart = await Bun.file(path).text();
}
finally
{
    await temp.rm(dir, { recursive: true });
}
