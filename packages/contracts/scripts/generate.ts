for (const [name, s] of definitions)
{
    const fields = Object.entries(s.properties!);
    go += `type ${name} struct {\n${
        fields.map(([k, v]) => `${cap(k)} ${goType(name, k, v)}`).join("\n")
    }\n}\n`;
    go += `func read${name}(r reader) ${name} { var v ${name}\n`;
    dart += `class ${name} {\n const ${name}({${
        fields.map(([k]) => `required this.${k}`).join(",")
    }});\n${fields.map(([k, v]) => `final ${dartType(name, k, v)} ${k};`).join("\n")}\n`;
    const readDart: string[] = [];
    let dartWrite = `void _write(_Writer w) {\n`;
    let goWrite = `func (v ${name}) write(w *bytes.Buffer) {\n`;
    for (const [key, v] of fields)
    {
        const g = "v." + cap(key);
        if (v.type === "integer")
        {
            go += `${g} = r.uint(${v.maximum})\n`;
            readDart.push(`${key}: r.uint(${v.maximum})`);
            goWrite += `if ${g} > ${v.maximum} { panic(ErrPacket) }; put(w,${g})\n`;
            dartWrite += `w.uint(${key},${v.maximum});\n`;
        }
        else if (v.type === "string")
        {
            go += `${g} = r.str(${v.maxLength})\n`;
            readDart.push(`${key}: r.string(${v.maxLength})`);
            goWrite +=
                `if len(${g}) > ${v.maxLength} || !utf8.ValidString(${g}) {panic(ErrPacket)}; put(w,uint32(len(${g}))); w.WriteString(${g})\n`;
            dartWrite += `w.string(${key},${v.maxLength});\n`;
        }
        else if (v.type === "array")
        {
            const item = name + cap(key) + "Item";
            go +=
                `${g} = make([]${item},r.uint(${v.maxItems})); for i := range ${g} { ${g}[i] = read${item}(r) }\n`;
            readDart.push(
                `${key}: List.generate(r.uint(${v.maxItems}), (_) => ${item}._read(r), growable: false)`,
            );
            goWrite +=
                `if len(${g}) > ${v.maxItems} {panic(ErrPacket)}; put(w,uint32(len(${g}))); for _,item:=range ${g} {item.write(w)}\n`;
            dartWrite +=
                `w.uint(${key}.length,${v.maxItems}); for(final item in ${key}) { item._write(w); }\n`;
        }
        else
        {
            throw new Error("Unsupported wire type");
        }
    }
    go += `return v\n}\n` + goWrite + ` }\n`;
    dart += `static ${name} _read(_Reader r) => ${name}(${readDart.join(",")});\n`
        + dartWrite
        + ` }\n`;
    const packet = packets.find((p) => p.name === name);
    if (packet)
    {
        go += `func Decode${name}(b []byte) (v ${name}, err error) {
 defer func(){if recover()!=nil {err=ErrPacket}}()
 if len(b)<2 || len(b)>MaxPacketBytes || b[0]!=1 || b[1]!=${packet.opcode} {return v,ErrPacket}; r:=reader{bytes.NewReader(b[2:])}; v=read${name}(r); if r.Len()!=0 {return v,ErrPacket}; return v,nil
}
func Encode${name}(v ${name}) (b []byte, err error) {
 defer func(){if recover()!=nil {err=ErrPacket}}(); w:=new(bytes.Buffer); w.Write([]byte{1,${packet.opcode}}); v.write(w); if w.Len()>MaxPacketBytes {return nil,ErrPacket}; return w.Bytes(),nil
}
`;
        dart +=
            `static ${name} decode(Uint8List b) { if(b.length<2 || b.length>maxWorldPacketBytes || b[0]!=1 || b[1]!=${packet.opcode}) { throw const FormatException('Invalid world packet'); } final r=_Reader(b); final v=_read(r); if(r.offset!=b.length) { throw const FormatException('Trailing world bytes'); } return v; }
Uint8List encode() { final w=_Writer(); w.bytes.add([1,${packet.opcode}]); _write(w); final b=w.bytes.takeBytes(); if(b.length>maxWorldPacketBytes) { throw const FormatException('World packet too large'); } return b; }
`;
    }
    dart += `}\n`;
}
